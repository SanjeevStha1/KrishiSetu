// Normalizes any of Nepal's 77 districts to its closest of the 12 official AMPIS hubs
export function getAmpisHubForDistrict(mandi: NepalDistrictMandi): string {
  const map: Record<string, string> = {
    birtamod: 'birtamod',
    dharan: 'dharan',
    biratnagar: 'dharan',
    janakpur: 'dhalkebar',
    dhalkebar: 'dhalkebar',
    lalbandi: 'lalbandi',
    birgunj: 'lalbandi',
    kamalamai: 'kamalamai',
    kalimati: 'kalimati',
    kawasoti: 'kawasoti',
    pokhara: 'pokhara',
    butwal: 'butwal',
    nepalgunj: 'kohalpur',
    kohalpur: 'kohalpur',
    surkhet: 'birendranagar',
    birendranagar: 'birendranagar',
    dhangadhi: 'attariya',
    attariya: 'attariya',
    narayangarh: 'kawasoti',
  };
  if (mandi.id === 'jhapa') return 'birtamod';
  if (mandi.id === 'sunsari' || mandi.id === 'morang') return 'dharan';
  if (mandi.id === 'sarlahi') return 'lalbandi';
  if (mandi.id === 'dhanusha') return 'dhalkebar';
  if (mandi.id === 'banke') return 'kohalpur';
  if (mandi.id === 'surkhet') return 'birendranagar';
  if (mandi.id === 'kailali') return 'attariya';
  return map[mandi.nearestTerminalHubId] || 'kalimati';
}

